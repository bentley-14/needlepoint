"""Layer 5 dossier emission (case writer, PDFs, full-state bundle, markdown lint). Mixin for Orchestrator."""
from __future__ import annotations

import json
import logging
from datetime import datetime
from pathlib import Path
from .agents import (
    case_writer,
)
from .citation_audit import audit_citations
from . import verdict
from .state import (
    case_dir,
)

LOG = logging.getLogger("fraud_investigator.orchestrator")


class DossierMixin:

    def _run_case_writer(self) -> None:
        if self.dry_run:
            LOG.info("[dry-run] would call case_writer")
            return
        d = case_dir(self.state.case_id, self.state_root)
        self._stage("case_writer")
        # M6: deterministic citation audit — re-verify every evidence
        # citation (re-execute script commands, check URLs/paths) BEFORE the
        # attorney-facing documents are written. Skipped in calibration
        # (orchestrator-side re-execution would bypass the jail).
        citation_summary = audit_citations(
            self._evidence_payload(full=True),
            repo_root=self.working_dir or Path.cwd(),
            calibration=bool(self.calibration_as_of),
        )
        (d / "citation_audit.json").write_text(
            json.dumps(citation_summary, indent=2, default=str))
        if citation_summary.get("n_failed"):
            LOG.warning(
                f"  ⚠ citation audit: {citation_summary['n_failed']} of "
                f"{citation_summary['n_items']} citations failed verification "
                f"— see citation_audit.json; the case report must flag them")
        final_state = self.state.model_dump()
        final_state["citation_audit"] = {
            k: citation_summary.get(k)
            for k in ("skipped", "n_items", "n_failed", "by_status", "failures")
        }
        out = case_writer.run(
            subject=self.subject,
            case_id=self.state.case_id,
            final_state_summary=final_state,
            out_dir=d,
        )
        # Write the markdown deliverables
        (d / "00_README.md").write_text(out.case_summary)
        (d / "01_Case_Report.md").write_text(out.full_case_report)
        (d / "02_Layperson_Summary.md").write_text(out.layperson_summary)
        # Deterministic filing-decision scorecard — the plain-English "why this
        # filed/declined" rendered straight from compute_verdict's persisted
        # predicates (NOT the LLM). The legibility payoff of the verdict refactor.
        v = self.state.final_verdict
        (d / "FILING_DECISION.md").write_text(verdict.render_filing_decision_md(
            verdict=v.value if hasattr(v, "value") else str(v),
            rationale=self.state.verdict_rationale,
            predicates=self.state.verdict_predicates,
            evf=self.state.expected_value_factor,
            strength=self.state.strength_score,
            bucket=self.state.strength_bucket,
        ))
        # 03_Full_State.json is collated deterministically from the canonical
        # case state — NOT regenerated by the model (the model produced a lossy
        # ~5.6 KB retype of a ~240 KB state). This is the raw reason-trace; the
        # full per-agent trail lives in 04_Full_Investigation_Bundle.json.
        (d / "03_Full_State.json").write_text(
            json.dumps(self.state.model_dump(mode="json"), indent=2, default=str)
        )
        self.state.report_paths = {
            "filing_decision": str(d / "FILING_DECISION.md"),
            "case_summary": str(d / "00_README.md"),
            "full_case_report": str(d / "01_Case_Report.md"),
            "layperson_summary": str(d / "02_Layperson_Summary.md"),
            "full_state": str(d / "03_Full_State.json"),
        }
        # Lint the generated markdown for accidental-italics + render-fragility
        # issues (see scripts/lint_dossier_markdown.py + prompts/case_writer.md
        # formatting rules). Lint failures are LOGGED, not fatal — the dossier
        # still ships, but the warnings surface for human review.
        try:
            self._lint_dossier_markdown(d)
        except Exception as e:
            LOG.warning(f"  dossier markdown lint failed: {e}")

        # Emit the full investigation bundle — every agent's parsed output
        # across every iteration + adversarial round. Too large to open in
        # the Streamlit viewer (1-3 MB typical), but downloadable so a law
        # firm can load it into Claude (or another LLM) and ask follow-up
        # questions about any specific evidence item / disposition / argument.
        try:
            self._emit_full_state_bundle(d)
        except Exception as e:
            LOG.warning(f"  full-state bundle emit failed: {e}")

        # Emit the law-firm-distribution PDF brief (FCA qui tam memorandum
        # structure under 31 U.S.C. §§ 3729-3733). Reads the bundle for per-
        # iter detail; falls back to summary.json alone if bundle absent.
        try:
            self._emit_counsel_memorandum_pdf(d)
        except Exception as e:
            LOG.warning(f"  counsel memorandum PDF emit failed: {e}")

        # Also emit the court-ready qui tam complaint PDF (06_Qui_Tam_Complaint
        # .pdf) — a separate document in the same bundle, formatted as a real
        # federal complaint with caption block, sequential paragraph numbering,
        # and lettered prayer for relief.
        try:
            self._emit_qui_tam_complaint_pdf(d)
        except Exception as e:
            LOG.warning(f"  qui tam complaint PDF emit failed: {e}")


    def _emit_counsel_memorandum_pdf(self, dossier_dir: Path) -> Path | None:
        """Generate the 05_Counsel_Memorandum.pdf law-firm brief.

        Best-effort — if reportlab is not installed or the bundle is missing
        critical fields, logs a warning and returns None. The MD deliverables
        ship regardless.
        """
        try:
            from . import pdf_brief
        except ImportError as e:
            LOG.warning(f"  pdf_brief module import failed: {e}; skipping PDF")
            return None
        try:
            out = pdf_brief.build_from_case_dir(dossier_dir)
            kb = out.stat().st_size / 1024
            LOG.info(f"  counsel memorandum: {out.name} ({kb:.0f} KB)")
            self.state.report_paths["counsel_memorandum_pdf"] = str(out)
            return out
        except Exception as e:
            LOG.warning(f"  PDF generation failed: {e}")
            return None


    def _emit_qui_tam_complaint_pdf(self, dossier_dir: Path) -> Path | None:
        """Generate the 06_Qui_Tam_Complaint.pdf — court-ready complaint.

        Same best-effort handling as the counsel memorandum: if reportlab is
        missing or the data is thin, log a warning and return None.
        """
        try:
            from . import pdf_qui_tam
        except ImportError as e:
            LOG.warning(f"  pdf_qui_tam module import failed: {e}; skipping PDF")
            return None
        try:
            out = pdf_qui_tam.build_from_case_dir(dossier_dir)
            kb = out.stat().st_size / 1024
            LOG.info(f"  qui tam complaint: {out.name} ({kb:.0f} KB)")
            self.state.report_paths["qui_tam_complaint_pdf"] = str(out)
            return out
        except Exception as e:
            LOG.warning(f"  qui tam PDF generation failed: {e}")
            return None


    def _collect_execution_trace(self) -> list[dict]:
        """Concatenate the full GUI event stream for this case.

        Returns every event (tool call, tool result, reasoning turn, log) that
        was streamed to ``events.jsonl`` during this case's run(s), merged in
        timestamp order. A resumed case spans multiple runs: each run drops a
        ``case_id.txt`` marker in its run dir, so all runs sharing this
        ``case_id`` are gathered. The current run is always included. Returns
        ``[]`` when there is no event sink (e.g. a headless/no-GUI run).
        """
        if self.event_sink is None:
            return []
        cur_events = self.event_sink.path
        run_dir = cur_events.parent
        runs_dir = run_dir.parent
        cid = self.state.case_id
        # Marker so future resume-runs can find THIS run's events by case_id.
        try:
            (run_dir / "case_id.txt").write_text(cid)
        except Exception:
            pass
        event_files: list[Path] = []
        if cur_events.exists():
            event_files.append(cur_events)
        # Marker-based discovery: cheap, covers runs that wrote case_id.txt.
        marker_run_dirs: set[Path] = set()
        for marker in sorted(runs_dir.glob("*/case_id.txt")):
            if marker.parent == run_dir:
                continue
            try:
                if marker.read_text().strip() != cid:
                    continue
            except Exception:
                continue
            marker_run_dirs.add(marker.parent)
            ej = marker.parent / "events.jsonl"
            if ej.exists():
                event_files.append(ej)
        # Fallback: markerless runs (e.g., crashed/interrupted before finalize,
        # or pre-dating the eager marker-write in __init__). Peek at each
        # markerless run's first event and pull it in if its case_id matches.
        # This is what was missing for the Cedar case — its original run never
        # reached finalize, so no marker, so the bundle's execution_trace lost
        # every tool call from the run that did the real investigation work.
        for d in sorted(runs_dir.iterdir()):
            if not d.is_dir() or d == run_dir or d in marker_run_dirs:
                continue
            ej = d / "events.jsonl"
            if not ej.exists():
                continue
            try:
                with ej.open() as f:
                    first_line = f.readline().strip()
                if not first_line:
                    continue
                first = json.loads(first_line)
                if (first.get("payload") or {}).get("case_id") != cid:
                    continue
            except Exception:
                continue
            event_files.append(ej)
        events: list[dict] = []
        for ej in event_files:
            try:
                for line in ej.read_text().splitlines():
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        events.append(json.loads(line))
                    except Exception:
                        pass
            except Exception:
                continue
        events.sort(key=lambda e: e.get("ts", ""))
        return events


    def _emit_full_state_bundle(self, dossier_dir: Path) -> Path:
        """Write a consolidated JSON bundle of EVERY agent's parsed output.

        Output: ``04_Full_Investigation_Bundle.json``. Shape::

            {
              "case_id": str,
              "subject": str,
              "schema_version": "2",
              "summary": <full state.model_dump()>,
              "iterations": [
                {
                  "iteration": int, "phase": "build" | "rebuttal_closing",
                  "investigator": <investigator.parsed.json or null>,
                  "counsel_build": <counsel_build.parsed.json or null>,
                  "counsel_first_chair_review": <...parsed.json or null>,
                  "counsel_rebuttal": <...parsed.json or null>,
                  "counsel_disposition": <...parsed.json or null>,
                },
                ...
              ],
              "adversarial_rounds": [
                {
                  "round": int,
                  "defense": <defense.parsed.json or null>,
                  "legal_adv_response": <...parsed.json or null>,
                  "rebuttal_investigator": <...parsed.json or null>,
                },
                ...
              ],
              "case_writer": <case_writer.parsed.json or null>,
              "execution_trace": [ {ts, stage, type, payload}, ... ],
              "manifest": {"path_index": {step: relative_path, ...}},
            }

        Per-step parsed.json files are inlined to keep the law firm's review
        flow single-file. ``execution_trace`` is the full tool-by-tool stream
        streamed to the GUI (every tool call, result, and reasoning turn),
        with all runs of a resumed case concatenated in timestamp order. The
        bundle is JSON because Claude / GPT-4 / Gemini all ingest JSON
        natively. Total expected size: 1-3 MB per case.
        """
        case_root = case_dir(self.state.case_id, self.state_root)

        def _read_parsed(rel: str) -> dict | None:
            p = case_root / rel
            if not p.exists():
                return None
            try:
                return json.loads(p.read_text())
            except Exception as e:
                return {"_load_error": str(e), "_path": rel}

        # Iteration steps (Phase A + Phase B both live under iter-NN/)
        iter_dirs = sorted(case_root.glob("iter-*"))
        iterations: list[dict] = []
        for d in iter_dirs:
            try:
                it_num = int(d.name.split("-")[-1])
            except ValueError:
                continue
            iter_phase = next(
                (it.phase for it in self.state.iterations if it.iteration == it_num),
                "build",
            )
            iterations.append({
                "iteration": it_num,
                "phase": iter_phase,
                "investigator":                _read_parsed(f"{d.name}/investigator.parsed.json"),
                "counsel_build":               _read_parsed(f"{d.name}/counsel_build.parsed.json"),
                "counsel_first_chair_review":  _read_parsed(f"{d.name}/counsel_first_chair_review.parsed.json"),
                "counsel_rebuttal":            _read_parsed(f"{d.name}/counsel_rebuttal.parsed.json"),
                "counsel_disposition":         _read_parsed(f"{d.name}/counsel_disposition.parsed.json"),
            })

        # Adversarial rounds
        adv_dirs = sorted(case_root.glob("adv-r*"))
        adv_rounds: list[dict] = []
        for d in adv_dirs:
            try:
                rn = int(d.name.split("-r")[-1])
            except ValueError:
                continue
            adv_rounds.append({
                "round": rn,
                "defense":                _read_parsed(f"{d.name}/defense.parsed.json"),
                "legal_adv_response":     _read_parsed(f"{d.name}/legal_adv_response.parsed.json"),
                "rebuttal_investigator":  _read_parsed(f"{d.name}/rebuttal_investigator.parsed.json"),
            })

        # Path index — every original parsed.json file the bundle inlined,
        # so a reviewer can re-trace any value back to its source file.
        path_index: dict[str, str] = {}
        for d in iter_dirs + adv_dirs:
            for p in d.glob("*.parsed.json"):
                key = f"{d.name}/{p.stem.replace('.parsed', '')}"
                path_index[key] = str(p.relative_to(case_root))
        if (case_root / "case_writer.parsed.json").exists():
            path_index["case_writer"] = "case_writer.parsed.json"

        execution_trace = self._collect_execution_trace()

        bundle = {
            "case_id": self.state.case_id,
            "subject": self.state.subject,
            "schema_version": "2",
            "generated_at": datetime.utcnow().isoformat() + "Z",
            "warning_for_reviewers": (
                "This file consolidates every agent's parsed output across "
                "every iteration and adversarial round, PLUS the full "
                "tool-by-tool execution trace under `execution_trace` (every "
                "tool call, result, and reasoning turn streamed during the "
                "run; all runs of a resumed case are concatenated in "
                "timestamp order). It is intentionally too large for "
                "in-browser preview. Recommended workflow: download, load "
                "into Claude / GPT-4 / Gemini, then ask the LLM specific "
                "questions about any evidence item, disposition, tool call, "
                "or the chain of reasoning behind any conclusion. The "
                "human-readable narrative lives in 01_Case_Report.md; this "
                "file is the complete evidence + reasoning + execution audit "
                "trail."
            ),
            "summary": self.state.model_dump(mode="json"),
            "iterations": iterations,
            "adversarial_rounds": adv_rounds,
            "case_writer": _read_parsed("case_writer.parsed.json"),
            "execution_trace": execution_trace,
            "manifest": {"path_index": path_index},
        }

        out_path = dossier_dir / "04_Full_Investigation_Bundle.json"
        out_path.write_text(json.dumps(bundle, indent=2, default=str))
        size_kb = out_path.stat().st_size / 1024
        LOG.info(f"  full-state bundle: {out_path.name} ({size_kb:.0f} KB, "
                 f"{len(iterations)} iter(s) + {len(adv_rounds)} adv round(s) "
                 f"+ {len(execution_trace)} trace events)")
        # Make the bundle's path easily discoverable via report_paths
        self.state.report_paths["full_bundle"] = str(out_path)
        return out_path


    def _lint_dossier_markdown(self, dossier_dir: Path) -> None:
        """Run the markdown linter on freshly-written dossier files.

        Findings are LOGGED (not raised). The dossier ships either way, but
        the warnings let the user review formatting issues before the dossier
        gets promoted to investigations/. See scripts/lint_dossier_markdown.py
        and prompts/case_writer.md for the rule set.
        """
        # Lazy import via subprocess so the orchestrator doesn't import scripts/
        import subprocess
        import sys
        repo_root = Path(__file__).resolve().parents[3]
        lint = repo_root / "scripts" / "lint_dossier_markdown.py"
        if not lint.exists():
            LOG.debug("  lint script not found; skipping")
            return
        r = subprocess.run(
            [sys.executable, str(lint), str(dossier_dir)],
            capture_output=True, text=True, timeout=30,
        )
        # Parse "Summary: N file(s) with M finding(s) (X high severity)"
        for line in r.stdout.splitlines():
            if line.startswith("Summary:"):
                LOG.info(f"  dossier lint — {line.strip()}")
                if "0 finding" not in line:
                    LOG.warning(
                        f"  dossier markdown has formatting issues — review "
                        f"with: python scripts/lint_dossier_markdown.py {dossier_dir}"
                    )
                break

